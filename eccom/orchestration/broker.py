"""Managed MQTT broker lifecycle.

When a scenario needs a broker and the hosts configuration says managed=True,
the runner starts a broker Docker container on the designated host (via that
host's deployment — locally or over SSH) before the agents, waits until the
broker accepts TCP connections, and removes the container after the run.
Which broker is the scenario's choice (``protocol.mqtt.broker.implementation``):
mosquitto, one event loop on one core, or NanoMQ, multi-threaded.

The broker always runs from a config the runner generates into
``<run-dir>/broker/`` (``mosquitto.conf`` or ``nanomq.conf``) and ships to the
broker host, so the flow-control limits the scenario asks for
(``protocol.mqtt.broker``), the TCP_NODELAY setting and the TLS material are
recorded with the run rather than inherited from the image's defaults.
"""

from __future__ import annotations

import asyncio
import contextlib
import logging
import shutil
import time
from pathlib import Path

from eccom.core.config import BrokerImplementation, ProtocolConfig
from eccom.core.hosts import BrokerConfig
from eccom.orchestration.deployment import Deployment

logger = logging.getLogger(__name__)

_REACHABLE_TIMEOUT_S = 60.0  # first run may pull the image

# The image each implementation runs from unless the hosts file names one.
# NanoMQ's base image is built without TLS; the slim variant adds it. 0.24.14
# is the newest release whose inbound QoS 1/2 quota (1024 per connection) is
# refilled when the PUBACK goes out: 0.25.x (checked 0.25.6) never
# refills it and disconnects every MQTT 5 publisher after exactly 1024
# acknowledged messages (reason 0x93).
DEFAULT_IMAGES: dict[BrokerImplementation, str] = {
    "mosquitto": "eclipse-mosquitto:2",
    "nanomq": "emqx/nanomq:0.24.14-slim",
}

MOSQUITTO_DEFAULT_INFLIGHT = 20  # what mosquitto applies when its config says nothing

_MOSQUITTO_CONF = """listener {port}
allow_anonymous true
# Per-client QoS 1/2 flow control; 0 = unlimited. mosquitto's own defaults are
# 20 / 1000. Set from protocol.mqtt.broker in the scenario.
max_inflight_messages {max_inflight}
max_queued_messages {max_queued}
# Largest packet accepted, in bytes. mosquitto 2.1 defaults to 2000000 and
# disconnects a client that exceeds it ("oversize packet"); 2.0 had no limit.
# Set from protocol.mqtt.broker in the scenario (default: the MQTT maximum).
max_packet_size {max_packet_size}
# Nagle's algorithm, from protocol.tcp_nodelay in the scenario: true = off, as
# on the eccom clients and asyncio's HTTP sockets. mosquitto's own default is
# false, which holds a PUBLISH or PUBACK behind the previous unacknowledged one.
set_tcp_nodelay {tcp_nodelay}
"""

_MOSQUITTO_TLS = """certfile /mosquitto/config/server.pem
keyfile /mosquitto/config/server-key.pem
"""

# NanoMQ's per-subscriber QoS 1/2 queue cannot be unlimited: it is a ring of
# message pointers sized at connect (nni_lmq), and what no longer fits is
# dropped ("msg lost due to reach the limit of lmq" in its log). 2^20 entries
# cost 8 MiB per subscriber and hold the backlog of any run of this framework.
NANOMQ_UNLIMITED_QUEUE = 1_048_576

_NANOMQ_MOUNT = "/eccom/broker"

_NANOMQ_CONF = """# Generated by eccom for {image} (HOCON).
mqtt {{
    # QoS 1/2 messages queued per subscriber (NanoMQ's shipped default is 2048):
    # a subscriber further behind than this silently loses the excess. From
    # protocol.mqtt.broker.max_queued_messages; 0 (unlimited) becomes {unlimited}.
    max_mqueue_len = {max_queued}
    # Largest packet accepted, in bytes, also announced as Maximum Packet Size
    # in CONNACK (NanoMQ's own default is 10 MiB). From
    # protocol.mqtt.broker.max_packet_size.
    max_packet_size = {max_packet_size}
}}
# NanoMQ takes no setting for its inbound QoS 1/2 window: 1024 unacknowledged
# publishes per connection at compile time, enforced by disconnecting the
# client (reason 0x93) rather than queueing, and not announced as Receive
# Maximum; so protocol.mqtt.broker.max_inflight_messages has no counterpart
# here. Every accepted connection runs with TCP_NODELAY and there is no
# switch, which is protocol.tcp_nodelay: true (the scenario rejects false).
{listener}
log {{
    to = [console]
    level = warn
}}
auth {{
    allow_anonymous = true
}}
"""

_NANOMQ_TCP_LISTENER = """listeners.tcp {{
    bind = "0.0.0.0:{port}"
}}"""

_NANOMQ_TLS_LISTENER = """listeners.ssl {{
    bind = "0.0.0.0:{port}"
    keyfile = "{mount}/server-key.pem"
    certfile = "{mount}/server.pem"
    # unused with verify_peer false, but NanoMQ logs an error without a readable one
    cacertfile = "{mount}/server.pem"
    verify_peer = false
    fail_if_no_peer_cert = false
}}"""


class MqttBrokerManager:
    """Starts, waits for and removes the managed broker container of one run."""

    def __init__(
        self,
        config: BrokerConfig,
        deployment: Deployment,
        protocol: ProtocolConfig,
        scenario_dir: Path,
    ) -> None:
        self._config = config
        self._deployment = deployment
        self._mqtt = protocol.mqtt
        self._tls = protocol.tls
        self._tcp_nodelay = protocol.tcp_nodelay
        self._scenario_dir = scenario_dir
        self._implementation = protocol.mqtt.broker.implementation
        self._image = config.docker_image or DEFAULT_IMAGES[self._implementation]
        self._run_dir: Path | None = None

    async def start(self, run_dir: Path) -> None:
        """Generate the config, start the container and wait for the port.

        run_dir: the local run directory; the config lands in its broker/ subdir.
        Raises RuntimeError when docker run fails, TimeoutError when the port never opens.
        """
        self._run_dir = run_dir
        # Remove any leftover container from an aborted previous run.
        await self._deployment.run_command(["docker", "rm", "-f", self._config.container_name])
        config_dir = await self._stage_config(run_dir)
        port = self._mqtt.endpoint.port
        command = [
            "docker",
            "run",
            "-d",
            "--name",
            self._config.container_name,
            "-p",
            f"{port}:{port}",
        ]
        if self._implementation == "mosquitto":
            # the default entrypoint picks up /mosquitto/config/mosquitto.conf
            command += ["-v", f"{config_dir}:/mosquitto/config:ro"]
            if self._tls.enabled:
                # --user root sidesteps in-container key file ownership
                command += ["--user", "root"]
        else:
            command += ["-v", f"{config_dir}:{_NANOMQ_MOUNT}:ro"]
        # the host's resource caps apply to the broker as much as to the agent:
        # with unlimited queues a backlog of undelivered messages lives in it
        command += self._deployment.container_flags()
        command.append(self._image)
        if self._implementation == "nanomq":
            # the image's entrypoint turns a leading option into `nanomq start --conf ...`
            command += ["--conf", f"{_NANOMQ_MOUNT}/nanomq.conf"]
        exit_code, output = await self._deployment.run_command(command)
        if exit_code != 0:
            raise RuntimeError(
                f"starting the MQTT broker container failed (is Docker available "
                f"on the broker host?):\n{output.strip()}"
            )
        logger.info(
            "MQTT broker container %s (%s) started, waiting for %s:%d",
            self._config.container_name,
            self._image,
            self._mqtt.endpoint.host,
            port,
        )
        await self._wait_reachable()

    async def stop(self) -> None:
        """Keep the broker's own log as ``broker/<implementation>.log`` in the
        run dir (mosquitto: its version and every disconnect with its reason;
        NanoMQ: every client's online/offline line and every dropped message),
        then remove the container."""
        name = self._config.container_name
        _, log = await self._deployment.run_command(["docker", "logs", name])
        if self._run_dir is not None:
            (self._run_dir / "broker" / f"{self._implementation}.log").write_text(
                log, encoding="utf-8", newline="\n"
            )
        await self._deployment.run_command(["docker", "rm", "-f", name])
        logger.info("MQTT broker container %s removed", name)

    async def _stage_config(self, run_dir: Path) -> str:
        """Assemble the broker's config (and TLS files) under run_dir/broker and
        make it available on the broker host; returns the host path to mount."""
        broker_dir = run_dir / "broker"
        broker_dir.mkdir(parents=True, exist_ok=True)
        if self._tls.enabled:
            assert self._tls.cert_file is not None and self._tls.key_file is not None
            shutil.copyfile(self._scenario_dir / self._tls.cert_file, broker_dir / "server.pem")
            shutil.copyfile(self._scenario_dir / self._tls.key_file, broker_dir / "server-key.pem")
        conf = self._mosquitto_conf() if self._implementation == "mosquitto" else self._nanomq_conf()
        (broker_dir / f"{self._implementation}.conf").write_text(
            conf, encoding="utf-8", newline="\n"
        )
        return await self._deployment.push_run_dir(run_dir, "broker")

    def _mosquitto_conf(self) -> str:
        broker = self._mqtt.broker
        max_inflight = broker.max_inflight_messages
        conf = _MOSQUITTO_CONF.format(
            port=self._mqtt.endpoint.port,
            max_inflight=MOSQUITTO_DEFAULT_INFLIGHT if max_inflight is None else max_inflight,
            max_queued=broker.max_queued_messages,
            max_packet_size=broker.max_packet_size,
            tcp_nodelay=str(self._tcp_nodelay).lower(),
        )
        if self._tls.enabled:
            conf += _MOSQUITTO_TLS
        return conf

    def _nanomq_conf(self) -> str:
        broker = self._mqtt.broker
        port = self._mqtt.endpoint.port
        if self._tls.enabled:
            listener = _NANOMQ_TLS_LISTENER.format(port=port, mount=_NANOMQ_MOUNT)
        else:
            listener = _NANOMQ_TCP_LISTENER.format(port=port)
        return _NANOMQ_CONF.format(
            image=self._image,
            max_queued=broker.max_queued_messages or NANOMQ_UNLIMITED_QUEUE,
            unlimited=NANOMQ_UNLIMITED_QUEUE,
            max_packet_size=broker.max_packet_size,
            listener=listener,
        )

    async def _wait_reachable(self) -> None:
        deadline = time.monotonic() + _REACHABLE_TIMEOUT_S
        host, port = self._mqtt.endpoint.host, self._mqtt.endpoint.port
        while time.monotonic() < deadline:
            try:
                _, writer = await asyncio.wait_for(
                    asyncio.open_connection(host, port), timeout=2
                )
            except (OSError, TimeoutError, asyncio.TimeoutError):
                await asyncio.sleep(0.3)
                continue
            writer.close()
            with contextlib.suppress(OSError):
                await writer.wait_closed()
            return
        raise TimeoutError(
            f"MQTT broker did not become reachable at {host}:{port} "
            f"within {_REACHABLE_TIMEOUT_S}s"
        )
